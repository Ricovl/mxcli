package javaactions

import (
	"strings"
	"testing"
)

// ako/mxcli#1700 (mendixlabs/mxcli#1653): mxbuild writes a Java action's
// documentation as a javadoc block above `public class`, and GenerateSource
// wrote none — so every `create [or modify] java action` removed the block a
// build had written, and the next build put it back.
//
// The goldens JA_Doc*.java.golden are the files mxbuild 11.13.0
// (`--target=deploy`) left for actions whose documentation was set to exactly
// the strings below — written straight into the model, since a `/** … */` doc
// comment trims each line and cannot hold a `*/`. JA_Doc2 and JA_Doc6 were
// deleted before the build, so mxbuild generated them from nothing; the others
// it regenerated over the file mxcli had written without a block. What the
// documentation became, measured:
//
//   - one ` * ` line per line, `\r\n`, `\r` and `\n` each ending one — so a
//     leading or trailing break gives an empty ` * ` line, and spaces and tabs
//     are kept as they are, trailing ones included;
//   - a backslash is doubled unless a unicode escape follows it — `u` or `U`
//     and four hex digits — so javac cannot read `\user` as a broken one
//     (`\uuu0041`, legal Java, is doubled too);
//   - no documentation, no block; whitespace alone is documentation.
//
// A parameter's description is not written into the file (JA_Doc1 has one),
// and mxbuild refuses a documentation holding `*/` as a model error
// ("Documentation contains invalid characters, */ is not allowed").
var classDocCases = []struct {
	name     string
	doc      string
	userCode string // "" — generated by mxbuild from no file at all
	params   []*JavaActionParameter
}{
	{"JA_Doc1", "Formats an amount as text with two decimals.", "return null;",
		[]*JavaActionParameter{{Name: "Amount", Description: "The amount to format.", ParameterType: &DecimalType{}}}},
	{"JA_Doc2", "Line one.\n\nLine three.", "", nil},
	{"JA_Doc3", "Ends with a newline.\n", "return null;", nil},
	{"JA_Doc4", "  Leading spaces\ttab\nTrailing spaces  ", "return null;", nil},
	{"JA_Doc6", "Café — naïve ünïcode, emoji \U0001F600, nbsp\u00a0and line separator \u2028 kept", "", nil},
	{"JA_Doc7", "CRLF one\r\nCRLF two\r\n", "return null;", nil},
	{"JA_Doc8", "\nStarts with a newline", "return null;", nil},
	{"JA_Doc9", "", "return null;", nil},
	{"JA_Doc10", "   ", "return null;", nil},
	{"JA_Doc11", `doubled: a \user b, \n, \u004G, \uuu0041, \u00 x; kept: \u00e9 \U0041 \uAbCd \u00411; end\`, "return null;", nil},
	{"JA_Doc12", "Lone CR\rhere\n\n\nthree newlines", "return null;", nil},
	{"JA_Doc13", `three \\\u0041 four \\\\u0041`, "return null;", nil},
	{"JA_Doc14", " * star line\n**bold** /** nested @param x {@code y} <b>html</b>", "return null;", nil},
	{"JA_Doc15", "\t", "return null;", nil},
}

func TestGenerateSource_ClassJavadocMatchesMxbuild(t *testing.T) {
	stub := `throw new com.mendix.systemwideinterfaces.MendixRuntimeException("Java action was not implemented");`
	for _, c := range classDocCases {
		t.Run(c.name, func(t *testing.T) {
			golden := readGolden(t, c.name)
			existing, userCode := golden, c.userCode
			if userCode == "" {
				existing, userCode = "", stub
			}
			imports, extra := RetainSections(existing, nil, "")
			got := GenerateSource("MyFirstModule", c.name, userCode, c.params, &StringType{}, imports, extra, c.doc)
			if c.userCode == "" {
				// mxcli pads the user code with a blank line on each side.
				got = strings.Replace(got, "// BEGIN USER CODE\r\n\r\n", "// BEGIN USER CODE\r\n", 1)
				got = strings.Replace(got, "\r\n\r\n\t\t// END USER CODE", "\r\n\t\t// END USER CODE", 1)
			}
			if got != golden {
				t.Errorf("generated source differs from mxbuild's:\n%s", lineDiff(golden, got))
			}
		})
	}
}

// The block replaces the one in the file: regenerating with other
// documentation leaves one block, and with none, no block — the documentation
// is the model's, not one of the sections a regeneration retains.
func TestGenerateSource_ClassJavadocIsRegeneratedNotRetained(t *testing.T) {
	golden := readGolden(t, "JA_Doc2")
	imports, extra := RetainSections(golden, nil, "")
	got := GenerateSource("MyFirstModule", "JA_Doc2", "return null;", nil, &StringType{}, imports, extra, "Other.")
	if n := strings.Count(got, "/**\r\n * "); n != 1 || !strings.Contains(got, "/**\r\n * Other.\r\n */\r\npublic class JA_Doc2") {
		t.Errorf("want one block holding the new documentation (%d found):\n%s", n, got)
	}
	got = GenerateSource("MyFirstModule", "JA_Doc2", "return null;", nil, &StringType{}, imports, extra, "")
	if strings.Contains(got, "Line one.") || !strings.Contains(got, "UserAction;\r\n\r\npublic class JA_Doc2") {
		t.Errorf("want no block without documentation:\n%s", got)
	}
}
