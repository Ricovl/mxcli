package modelsdkbackend

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/mendixlabs/mxcli/mdl/types"
)

// Studio Pro's regeneration of a JavaScript action keeps the import list and
// the code between BEGIN EXTRA CODE and END EXTRA CODE. MDL can express neither
// (describe prints the extra code only as a comment), so a `create or modify`
// with an edited body must carry both over from the file on disk — otherwise a
// hand-restored helper is overwritten and the user code calling it breaks
// (mendixlabs/mxcli#1429).
const storedDistanceJS = `// This file was generated by Mendix Studio Pro.
//
// WARNING: Only the following code will be retained when actions are regenerated:
// - the import list
// - the code between BEGIN USER CODE and END USER CODE
// - the code between BEGIN EXTRA CODE and END EXTRA CODE
// Other code you write will be lost the next time you deploy the project.
import "mx-global";
import { Big } from "big.js";
import {
	sin,
	cos
} from "./trig";

// BEGIN EXTRA CODE
function deg2rad(deg) {
    return deg.times(Math.PI / 180);
}
// END EXTRA CODE

/**
 * @param {Big} latitude
 * @returns {Promise.<Big>}
 */
export async function GetDistance(latitude) {
	// BEGIN USER CODE
	return deg2rad(latitude);
	// END USER CODE
}
`

func TestWriteJavaScriptSourceFile_EditedBodyKeepsImportsAndExtraCode(t *testing.T) {
	dir := t.TempDir()
	b := &Backend{path: filepath.Join(dir, "App.mpr")}
	jsDir := b.jsActionSourceDir("WebMod")
	if err := os.MkdirAll(jsDir, 0o755); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(jsDir, "GetDistance.js")
	if err := os.WriteFile(path, []byte(storedDistanceJS), 0o644); err != nil {
		t.Fatal(err)
	}

	params := []*types.JavaActionParameter{{Name: "latitude", IsRequired: true, ParameterType: &types.DecimalType{}}}
	if err := b.WriteJavaScriptSourceFile("WebMod", "GetDistance", "return deg2rad(latitude).times(2);", params, &types.DecimalType{}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	src := string(got)
	for _, want := range []string{
		`import "mx-global";`,
		`import { Big } from "big.js";`,
		"import {\n\tsin,\n\tcos\n} from \"./trig\";",
		"// BEGIN EXTRA CODE\nfunction deg2rad(deg) {\n    return deg.times(Math.PI / 180);\n}\n// END EXTRA CODE",
		"\treturn deg2rad(latitude).times(2);",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("regenerated source lost %q:\n%s", want, src)
		}
	}
	// The imports precede the EXTRA CODE section, as Studio Pro writes them.
	if strings.Index(src, `import { Big }`) > strings.Index(src, "// BEGIN EXTRA CODE") {
		t.Errorf("imports written after the EXTRA CODE section:\n%s", src)
	}

	// Regenerating again is stable: nothing duplicated.
	if err := b.WriteJavaScriptSourceFile("WebMod", "GetDistance", "return deg2rad(latitude).times(2);", params, &types.DecimalType{}); err != nil {
		t.Fatal(err)
	}
	again, _ := os.ReadFile(path)
	if string(again) != src {
		t.Errorf("second regeneration changed the file:\n%s", again)
	}
}

// Control: with no file on disk the stub is the plain generated one — no
// imports and an empty EXTRA CODE section.
func TestWriteJavaScriptSourceFile_NewFileHasEmptySections(t *testing.T) {
	dir := t.TempDir()
	b := &Backend{path: filepath.Join(dir, "App.mpr")}
	if err := b.WriteJavaScriptSourceFile("WebMod", "Fresh", "return 1;", nil, nil); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(filepath.Join(b.jsActionSourceDir("WebMod"), "Fresh.js"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(got), "\nimport ") || !strings.Contains(string(got), "// BEGIN EXTRA CODE\n// END EXTRA CODE") {
		t.Errorf("new stub has unexpected sections:\n%s", got)
	}
}
