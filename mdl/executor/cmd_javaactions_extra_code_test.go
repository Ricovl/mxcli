// ako/mxcli#1702 (mendixlabs/mxcli#1658): `describe java action` printed only
// the body. A helper in the .java file's EXTRA CODE section, and the import it
// needs, were kept in place by `create or modify` — but executing the describe
// output on another project wrote a body calling a helper that no longer
// existed, and the project stopped compiling. describe now prints the imports a
// developer added at the top of the body and the section as `extra code $$ … $$`,
// so describe → exec rebuilds the same file.

const twiceHelper = "private static long twice(long n) {\n\treturn Objects.requireNonNull(n) * 2L;\n}"

func twiceAction(mod *model.Module) *javaactions.JavaAction {
	ja := &javaactions.JavaAction{
		ContainerID: mod.ID,
		Name:        "JA_Twice",
		ReturnType:  &javaactions.IntegerType{},
		Parameters: []*javaactions.JavaActionParameter{
			{Name: "N", IsRequired: true, ParameterType: &javaactions.IntegerType{}},
		},
	}
	ja.ID = nextID("ja")
	return ja
}

// writeTwiceSource writes the file of the report: generated by mxbuild, then a
// helper and an import added by hand.
func writeTwiceSource(t *testing.T, ja *javaactions.JavaAction) (mprPath, source string) {
	t.Helper()
	dir := t.TempDir()
	mprPath = filepath.Join(dir, "App.mpr")
	source = javaactions.GenerateSource("ModJ", "JA_Twice", "return twice(N);", ja.Parameters, ja.ReturnType,
		[]string{
			"import com.mendix.systemwideinterfaces.core.IContext;",
			"import com.mendix.systemwideinterfaces.core.UserAction;",
			"import java.util.Objects;",
		}, twiceHelper, "")
	javaDir := filepath.Join(dir, "javasource", "modj", "actions")
	if err := os.MkdirAll(javaDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(javaDir, "JA_Twice.java"), []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}
	return mprPath, source
}

type writtenSource struct {
	code      string
	params    []*javaactions.JavaActionParameter
	ret       javaactions.CodeActionReturnType
	imports   []string
	extraCode *string
	doc       string
}

// execJavaActionOnFreshProject runs s against a project that has module ModJ
// and no action, and returns what it handed WriteJavaSourceFile.
func execJavaActionOnFreshProject(t *testing.T, s *ast.CreateJavaActionStmt) writtenSource {
	t.Helper()
	mod := mkModule("ModJ")
	var w *writtenSource
	mb := &mock.MockBackend{
		IsConnectedFunc:      func() bool { return true },
		ListModulesFunc:      func() ([]*model.Module, error) { return []*model.Module{mod}, nil },
		ListJavaActionsFunc:  func() ([]*types.JavaAction, error) { return nil, nil },
		CreateJavaActionFunc: func(*javaactions.JavaAction) error { return nil },
		WriteJavaSourceFileFunc: func(_, _, code string, params []*javaactions.JavaActionParameter,
			ret javaactions.CodeActionReturnType, imports []string, extraCode *string, doc string) error {
			w = &writtenSource{code, params, ret, imports, extraCode, doc}
			return nil
		},
	}
	ctx, _ := newMockCtx(t, withBackend(mb), withHierarchy(mkHierarchy(mod)))
	assertNoError(t, execCreateJavaAction(ctx, s))
	if w == nil {
		t.Fatal("WriteJavaSourceFile was never called")
	}
	return *w
}

func TestDescribeJavaAction_ExtraCodeAndImportsRoundTrip(t *testing.T) {
	mod := mkModule("ModJ")
	ja := twiceAction(mod)
	mprPath, source := writeTwiceSource(t, ja)

	mb := &mock.MockBackend{
		IsConnectedFunc:          func() bool { return true },
		ReadJavaActionByNameFunc: func(string) (*javaactions.JavaAction, error) { return ja, nil },
	}
	ctx, buf := newMockCtx(t, withBackend(mb), withMprPath(mprPath))
	assertNoError(t, describeJavaAction(ctx, ast.QualifiedName{Module: "ModJ", Name: "JA_Twice"}))
	out := buf.String()
	for _, want := range []string{"import java.util.Objects;", "\nextra code $$\n" + twiceHelper + "\n$$;"} {
		if !strings.Contains(out, want) {
			t.Errorf("describe output lacks %q:\n%s", want, out)
		}
	}

	// Executed on a project without the file, the output rebuilds it byte for
	// byte — what the backend does with what exec hands it.
	s := findStmt[*ast.CreateJavaActionStmt](t, reparse(t, out), out)
	w := execJavaActionOnFreshProject(t, s)
	imports, extra := javaactions.RetainSections("", w.imports, w.extraCode)
	got := javaactions.GenerateSource("ModJ", "JA_Twice", w.code, w.params, w.ret, imports, extra, w.doc)
	if got != source {
		t.Errorf("describe → exec on a fresh project wrote another file:\n--- want\n%s\n--- got\n%s", source, got)
	}
}

// An omitted clause still keeps the stored section: exec says nothing about it
// (nil), and the backend then retains what the file holds. A stated one — even
// empty — replaces it.
func TestCreateJavaAction_ExtraCodeClauseReachesTheWriter(t *testing.T) {
	for _, c := range []struct {
		name, clause string
		want         *string
	}{
		{"omitted keeps the stored section", "", nil},
		{"stated", " extra code $$ int x; $$", strPtrExec("int x;")},
		{"stated empty clears it", " extra code $$ $$", strPtrExec("")},
	} {
		t.Run(c.name, func(t *testing.T) {
			s := parseOne[*ast.CreateJavaActionStmt](t,
				"create java action ModJ.JA_Twice(N: Integer not null) returns Integer as $$ return N; $$"+c.clause+";")
			w := execJavaActionOnFreshProject(t, s)
			switch {
			case c.want == nil && w.extraCode != nil:
				t.Errorf("extraCode = %q, want nil — an omitted clause must keep the stored section", *w.extraCode)
			case c.want != nil && (w.extraCode == nil || *w.extraCode != *c.want):
				t.Errorf("extraCode = %v, want %q", w.extraCode, *c.want)
			}
		})
	}
}

func strPtrExec(s string) *string { return &s }
